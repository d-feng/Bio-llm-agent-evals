"""
evals/report.py
---------------
Generates a formatted Markdown and/or Word benchmark report
from run_benchmark() or run_eval() results.
"""

import os
from datetime import datetime
from typing import Optional
import pandas as pd


# ---------------------------------------------------------------------------
# Markdown report
# ---------------------------------------------------------------------------

def generate_markdown_report(
    df: pd.DataFrame,
    agent_type: str = "ReAct",
    use_llm_judge: bool = False,
    output_path: str = None,
) -> str:
    """
    Generate a Markdown benchmark report from a results DataFrame.
    Returns the report as a string and optionally writes it to a file.
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    score_col = "FinalScore" if use_llm_judge else "ExactMatch"

    # Per-module summary
    summary = df.groupby("Module").agg(
        Tasks=(score_col, "count"),
        ExactMatch=("ExactMatch", "mean"),
        FinalScore=(score_col, "mean"),
        AvgJaccard=("Jaccard", "mean"),
    ).round(3).reset_index()

    overall_em    = df["ExactMatch"].mean()
    overall_final = df[score_col].mean()
    total         = len(df)
    passed        = int(df[score_col].sum())

    lines = []
    lines.append(f"# Genomic Agent Benchmark Report")
    lines.append(f"")
    lines.append(f"**Date:** {now}  ")
    lines.append(f"**Agent:** {agent_type}  ")
    lines.append(f"**Scoring:** Exact Match" + (" + LLM Judge fallback" if use_llm_judge else ""))
    lines.append(f"")
    lines.append(f"---")
    lines.append(f"")

    # Overall scores
    lines.append(f"## Overall Results")
    lines.append(f"")
    lines.append(f"| Metric | Score |")
    lines.append(f"|---|---|")
    lines.append(f"| Exact Match Accuracy | {overall_em:.1%} ({int(df['ExactMatch'].sum())}/{total}) |")
    if use_llm_judge:
        lines.append(f"| Final Score (+ LLM judge) | **{overall_final:.1%} ({passed}/{total})** |")
    lines.append(f"| Total Tasks | {total} |")
    lines.append(f"")

    # Per-module table
    lines.append(f"## Per-Module Results")
    lines.append(f"")
    lines.append(f"| Module | Tasks | Exact Match | {'Final Score |' if use_llm_judge else ''} Avg Jaccard |")
    lines.append(f"|---|---|---|{'---|' if use_llm_judge else ''}---|")

    for _, row in summary.iterrows():
        em_str    = f"{row['ExactMatch']:.1%}"
        fs_str    = f"{row['FinalScore']:.1%}"
        jac_str   = f"{row['AvgJaccard']:.3f}"
        fs_col    = f" {fs_str} |" if use_llm_judge else ""
        lines.append(f"| {row['Module']} | {int(row['Tasks'])} | {em_str} |{fs_col} {jac_str} |")

    lines.append(f"")

    # Detailed results per module
    lines.append(f"## Detailed Results")
    lines.append(f"")

    for module in sorted(df["Module"].unique()):
        module_df = df[df["Module"] == module]
        lines.append(f"### {module}")
        lines.append(f"")
        lines.append(f"| Question | Expected | Agent Output | {('Exact | Judge | Reason |' if use_llm_judge else 'Exact |')} ")
        lines.append(f"|---|---|---|{'---|---|---|' if use_llm_judge else '---|'}")

        for _, row in module_df.iterrows():
            q   = row["Question"][:70]
            exp = row["Expected"]
            out = str(row["Agent_Output"])[:80].replace("\n", " ")
            em  = "PASS" if row["ExactMatch"] else "FAIL"

            if use_llm_judge and row["LLMJudge"] is not None:
                judge  = "PASS" if row["LLMJudge"] else "FAIL"
                reason = str(row.get("LLMJudgeReason", ""))[:80]
                lines.append(f"| {q} | {exp} | {out} | {em} | {judge} | {reason} |")
            else:
                lines.append(f"| {q} | {exp} | {out} | {em} |")

        lines.append(f"")

    lines.append(f"---")
    lines.append(f"*Generated by Bio-llm-agent-evals*")

    report = "\n".join(lines)

    if output_path:
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(report)
        print(f"\nMarkdown report saved to: {output_path}")

    return report


