def generate_word_report(
    df: pd.DataFrame,
    agent_type: str = "ReAct",
    use_llm_judge: bool = False,
    output_path: str = None,
) -> str:
    """
    Generate a Word (.docx) benchmark report from a results DataFrame.
    Returns the output file path.
    """
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor
        from docx.enum.text import WD_ALIGN_PARAGRAPH
    except ImportError:
        print("python-docx not installed. Run: pip install python-docx")
        return None

    if output_path is None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_path = f"benchmark_report_{ts}.docx"

    now       = datetime.now().strftime("%Y-%m-%d %H:%M")
    score_col = "FinalScore" if use_llm_judge else "ExactMatch"

    summary = df.groupby("Module").agg(
        Tasks=(score_col, "count"),
        ExactMatch=("ExactMatch", "mean"),
        FinalScore=(score_col, "mean"),
        AvgJaccard=("Jaccard", "mean"),
    ).round(3).reset_index()

    overall_em    = df["ExactMatch"].mean()
    overall_final = df[score_col].mean()
    total         = len(df)
    passed        = int(df[score_col].sum())

    doc = Document()

    # Title
    title = doc.add_heading("Genomic Agent Benchmark Report", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Metadata
    doc.add_paragraph(f"Date: {now}")
    doc.add_paragraph(f"Agent: {agent_type}")
    doc.add_paragraph(f"Scoring: Exact Match" + (" + LLM Judge fallback" if use_llm_judge else ""))
    doc.add_paragraph()

    # Overall results
    doc.add_heading("Overall Results", level=1)
    tbl = doc.add_table(rows=1, cols=2)
    tbl.style = "Light Grid Accent 1"
    hdr = tbl.rows[0].cells
    hdr[0].text, hdr[1].text = "Metric", "Score"

    rows_data = [("Exact Match Accuracy", f"{overall_em:.1%} ({int(df['ExactMatch'].sum())}/{total})")]
    if use_llm_judge:
        rows_data.append(("Final Score (+ LLM judge)", f"{overall_final:.1%} ({passed}/{total})"))
    rows_data.append(("Total Tasks", str(total)))

    for label, value in rows_data:
        row = tbl.add_row().cells
        row[0].text, row[1].text = label, value

    doc.add_paragraph()

    # Per-module summary
    doc.add_heading("Per-Module Results", level=1)
    cols = ["Module", "Tasks", "Exact Match"] + (["Final Score"] if use_llm_judge else []) + ["Avg Jaccard"]
    tbl2 = doc.add_table(rows=1, cols=len(cols))
    tbl2.style = "Light Grid Accent 1"
    for i, col in enumerate(cols):
        tbl2.rows[0].cells[i].text = col

    for _, row in summary.iterrows():
        cells = tbl2.add_row().cells
        cells[0].text = row["Module"]
        cells[1].text = str(int(row["Tasks"]))
        cells[2].text = f"{row['ExactMatch']:.1%}"
        if use_llm_judge:
            cells[3].text = f"{row['FinalScore']:.1%}"
            cells[4].text = f"{row['AvgJaccard']:.3f}"
        else:
            cells[3].text = f"{row['AvgJaccard']:.3f}"

    doc.add_paragraph()

    # Detailed per-module results
    doc.add_heading("Detailed Results", level=1)
    for module in sorted(df["Module"].unique()):
        module_df = df[df["Module"] == module]
        doc.add_heading(module, level=2)

        det_cols = ["Question", "Expected", "Agent Output", "Exact"]
        if use_llm_judge:
            det_cols += ["Judge", "Reason"]
        tbl3 = doc.add_table(rows=1, cols=len(det_cols))
        tbl3.style = "Light List Accent 1"
        for i, col in enumerate(det_cols):
            tbl3.rows[0].cells[i].text = col

        for _, row in module_df.iterrows():
            cells = tbl3.add_row().cells
            cells[0].text = row["Question"][:80]
            cells[1].text = row["Expected"]
            cells[2].text = str(row["Agent_Output"])[:100].replace("\n", " ")
            cells[3].text = "PASS" if row["ExactMatch"] else "FAIL"
            if use_llm_judge and row["LLMJudge"] is not None:
                cells[4].text = "PASS" if row["LLMJudge"] else "FAIL"
                cells[5].text = str(row.get("LLMJudgeReason", ""))[:100]

        doc.add_paragraph()

    doc.save(output_path)
    print(f"Word report saved to: {output_path}")
    return output_path
